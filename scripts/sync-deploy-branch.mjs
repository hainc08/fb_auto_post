#!/usr/bin/env node
/**
 * Build the `deploy` branch from the current commit (normally main).
 *
 * `deploy` holds only what Hostinger needs to install + build + run — no tests,
 * planning docs, dev tooling or seed scripts. It has its own history (one commit
 * per sync), so main stays free for development.
 *
 *   npm run deploy:branch            # commit to local `deploy`
 *   npm run deploy:branch -- --push  # …and push it to origin
 *
 * Only committed files are used: commit your work on main first.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const BRANCH = 'deploy';
const WORKTREE = path.resolve('.deploy-worktree');

/** Everything the production build and runtime read. Keep in sync with package.json scripts. */
const DEPLOY_PATHS = [
  '.gitignore',
  '.env.example',
  'package.json',
  'package-lock.json',
  'tsconfig.json',
  'prisma/schema.prisma',
  'prisma/hostinger-schema.sql',
  'src',
  'client/.gitignore',
  'client/.env.example',
  'client/index.html',
  'client/package.json',
  'client/package-lock.json',
  'client/public',
  'client/src',
  'client/tsconfig.json',
  'client/tsconfig.app.json',
  'client/tsconfig.node.json',
  'client/vite.config.ts',
  'docs/DEPLOY_HOSTINGER.md',
];

const git = (args, cwd = process.cwd()) => execFileSync('git', args, { cwd, encoding: 'utf8' }).trim();
const push = process.argv.includes('--push');

if (git(['status', '--porcelain'])) {
  console.warn('⚠️  Working tree has uncommitted changes; they are NOT included. Only HEAD is used.\n');
}

const sourceSha = git(['rev-parse', 'HEAD']);
const sourceShort = sourceSha.slice(0, 7);
const sourceBranch = git(['rev-parse', '--abbrev-ref', 'HEAD']);

for (const p of DEPLOY_PATHS) {
  try {
    git(['cat-file', '-e', `${sourceSha}:${p}`]);
  } catch {
    throw new Error(`Missing in ${sourceShort}: ${p} (commit it or remove it from DEPLOY_PATHS)`);
  }
}

// Fresh worktree for the deploy branch (orphan on first run)
if (existsSync(WORKTREE)) git(['worktree', 'remove', '--force', WORKTREE]);
git(['worktree', 'prune']);

const branchExists = (() => {
  try {
    git(['rev-parse', '--verify', '--quiet', `refs/heads/${BRANCH}`]);
    return true;
  } catch {
    return false;
  }
})();

try {
  if (branchExists) {
    git(['worktree', 'add', WORKTREE, BRANCH]);
  } else {
    git(['worktree', 'add', '--detach', WORKTREE]);
    git(['checkout', '--orphan', BRANCH], WORKTREE);
  }

  // Replace the whole tree with the deploy paths from the source commit
  git(['rm', '-r', '-q', '--ignore-unmatch', '--cached', '.'], WORKTREE);
  git(['clean', '-f', '-d', '-q'], WORKTREE);
  git(['checkout', sourceSha, '--', ...DEPLOY_PATHS], WORKTREE);

  writeFileSync(
    path.join(WORKTREE, 'README.md'),
    `# Auto Post — deploy branch

Generated by \`npm run deploy:branch\` from \`${sourceBranch}@${sourceShort}\`. **Do not edit this branch**; change \`main\` and re-run the script.

- Build command: \`npm run build:prod && npm run db:deploy\`
- Entry file: \`dist/server.js\` · Node.js 22.x
- Guide: [docs/DEPLOY_HOSTINGER.md](docs/DEPLOY_HOSTINGER.md)
`
  );
  git(['add', '-A'], WORKTREE);

  if (!git(['status', '--porcelain'], WORKTREE)) {
    console.log(`✓ ${BRANCH} already matches ${sourceBranch}@${sourceShort}, nothing to commit.`);
  } else {
    git(['commit', '-q', '-m', `Deploy build from ${sourceBranch}@${sourceShort}`], WORKTREE);
    console.log(`✓ Committed ${BRANCH} ← ${sourceBranch}@${sourceShort}`);
  }

  if (push) {
    execFileSync('git', ['push', 'origin', BRANCH], { cwd: WORKTREE, stdio: 'inherit' });
    console.log(`✓ Pushed origin/${BRANCH}. Redeploy in hPanel if auto-deploy is off.`);
  } else {
    console.log(`  Push with: git push origin ${BRANCH}`);
  }
} finally {
  if (existsSync(WORKTREE)) git(['worktree', 'remove', '--force', WORKTREE]);
  rmSync(WORKTREE, { recursive: true, force: true });
}
